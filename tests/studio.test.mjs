import { test } from 'node:test';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { pathToFileURL } from 'node:url';
import path from 'node:path';

test('graph studio: layers, parameters, inspector, table, errors and saved settings', async () => {
  const browser = await chromium.launch({ args: ['--no-sandbox'] });
  try {
    const context = await browser.newContext({ offline: true, acceptDownloads: true });
    const page = await context.newPage(); const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.goto(pathToFileURL(path.resolve('index.html')).href);
    await page.waitForFunction(() => window.CAS?.ready);
    await page.getByTitle('Graph', { exact: true }).click();
    await page.getByRole('textbox', { name: 'Expression 1', exact: true }).fill('x^2');
    await page.getByRole('textbox', { name: 'Expression 2', exact: true }).fill('a*sin(x)');
    await page.waitForSelector('input[data-param="a"]');
    await page.getByLabel('Inspect at x', { exact: true }).fill('2');
    await page.getByLabel('Area lower bound').fill('0');
    await page.getByLabel('Area upper bound').fill('3');
    await page.getByLabel('Tangent', { exact: true }).check();
    const insights = await page.locator('#studio-insights strong').allTextContents();
    assert.deepEqual(insights, ['4', '4', '9']);
    assert.ok(await page.locator('#gplot canvas').evaluate(c => c.__grapher.items.some(i => i.tangent)));
    await page.locator('input[data-param="a"]').fill('2');
    await page.getByRole('button', { name: /Value table/ }).click();
    assert.equal(await page.locator('#studio-table tbody tr').count(), 21);
    const tableFirstRow = await page.locator('#studio-table tbody tr').first().locator('td').allTextContents();
    assert.deepEqual(tableFirstRow.slice(0, 2), ['-5', '25']);
    const downloadPromise = page.waitForEvent('download');
    await page.getByRole('button', { name: /CSV/ }).click();
    assert.equal((await downloadPromise).suggestedFilename(), 'cassycas-values.csv');
    await page.getByRole('textbox', { name: 'Expression 2', exact: true }).fill('sin(');
    await page.waitForFunction(() => !!document.querySelectorAll('.expression-error')[1].textContent);
    assert.ok(await page.locator('#gplot canvas').evaluate(c => c.__grapher.items.some(i => i.kind === 'fn' && !i.tangent)));
    await page.getByRole('button', { name: 'Hide expression 1', exact: true }).click();
    assert.equal(await page.locator('#gplot canvas').evaluate(c => c.__grapher.items.filter(i => !i.tangent).length), 0);
    await page.getByRole('button', { name: 'Show expression 1', exact: true }).click();
    await page.getByTitle('Settings', { exact: true }).click();
    await page.getByRole('combobox', { name: 'Appearance', exact: true }).selectOption('dark');
    await page.getByRole('combobox', { name: 'Display precision' }).selectOption('6');
    await page.getByRole('checkbox', { name: 'Graph grid', exact: true }).uncheck();
    await page.reload(); await page.waitForFunction(() => window.CAS?.ready);
    assert.equal(await page.evaluate(() => CAS.state.darkTheme), true);
    assert.equal(await page.evaluate(() => CAS.state.precision), 6);
    assert.equal(await page.evaluate(() => document.body.classList.contains('graph-no-grid')), true);
    await page.getByTitle('Graph', { exact: true }).click();
    assert.equal(await page.getByRole('textbox', { name: 'Expression 1', exact: true }).inputValue(), 'x^2');
    await page.getByRole('textbox', { name: 'Expression 2', exact: true }).fill('a*sin(x)');
    await page.waitForSelector('input[data-param="a"]');
    await page.getByTitle('Notebook', { exact: true }).click();
    await page.evaluate(() => CAS.run('a = 3'));
    await page.getByTitle('Graph', { exact: true }).click();
    await page.waitForFunction(() => { const g = document.querySelector('#gplot canvas')?.__grapher; return g?.items[1] && Math.abs(g.items[1].f(Math.PI/2) - 3) < 1e-9; });
    await page.getByTitle('Explore library', { exact: true }).click();
    await page.getByLabel('Search example notebooks').fill('no-such-topic-1234');
    assert.ok(await page.locator('.empty-search').isVisible());
    assert.deepEqual(errors, []);
    await context.close();
  } finally { await browser.close(); }
});
